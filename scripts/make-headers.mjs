// Generates out/_headers after `next build` (Cloudflare static assets format, also applied by scripts/serve-out.mjs in tests).
// The static export puts a few small inline scripts in every page. Instead of allowing all inline code ('unsafe-inline'),
// the policy lists the SHA-256 hash of exactly those scripts per page, so anything else, including injected script, is blocked.
// Re-run on every build: the hashes change when the app changes.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const out = 'out';

function supabaseOrigin() {
  let url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  if (!url && existsSync('.env.local')) {
    const m = /^NEXT_PUBLIC_SUPABASE_URL=(.+)$/m.exec(readFileSync('.env.local', 'utf8'));
    url = m?.[1]?.trim();
  }
  if (!url) throw new Error('NEXT_PUBLIC_SUPABASE_URL is not set: the policy must name the API origin it allows.');
  return new URL(url).origin;
}
const apiOrigin = supabaseOrigin();

const pages = [];
(function walk(dir) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) { if (f !== '_next') walk(p); } else if (f.endsWith('.html')) pages.push(p);
  }
})(out);

const sha = (text) => `'sha256-${createHash('sha256').update(text, 'utf8').digest('base64')}'`;
function routeOf(file) {
  const rel = relative(out, file).split(sep).join('/');
  if (rel === 'index.html') return '/';
  if (rel.endsWith('/index.html')) return `/${rel.slice(0, -'index.html'.length)}`;
  return `/${rel}`; // e.g. /404.html
}

const policy = (hashes) => [
  "default-src 'self'",
  `script-src 'self' ${hashes.join(' ')}`,
  "style-src 'self'",
  "img-src 'self'",
  "font-src 'self'",
  `connect-src 'self' ${apiOrigin}`,
  "manifest-src 'self'",
  "worker-src 'self'",
  "frame-ancestors 'none'",
  "base-uri 'none'",
  "form-action 'self'",
  "object-src 'none'",
].join('; ') + ';';

let text = `# Generated by scripts/make-headers.mjs. Do not edit.
/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=()
  Strict-Transport-Security: max-age=31536000
/sw.js
  Cache-Control: no-cache
/_next/static/*
  Cache-Control: public, max-age=31536000, immutable
/fonts/*
  Cache-Control: public, max-age=604800
`;
for (const file of pages.sort()) {
  const html = readFileSync(file, 'utf8');
  const hashes = [...html.matchAll(/<script(?![^>]*\ssrc=)[^>]*>([\s\S]*?)<\/script>/g)].map((m) => sha(m[1]));
  if (hashes.length === 0) throw new Error(`${file} has no inline scripts to hash; the page cannot hydrate under this policy`);
  text += `${routeOf(file)}\n  Content-Security-Policy: ${policy([...new Set(hashes)])}\n  Cache-Control: no-cache\n`;
}
writeFileSync(join(out, '_headers'), text);
console.log('_headers written for', pages.length, 'pages; API origin', apiOrigin);
